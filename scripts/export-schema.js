// scripts/export-schema.js — Canonical schema snapshot generator
// Reads the live catalog inside a READ ONLY transaction and writes db/schema.sql:
// extensions, sequences, functions, tables, constraints, indexes, triggers.
// Usage: node --env-file=.env scripts/export-schema.js [outFile]
"use strict";

const fs = require("fs");
const path = require("path");
const { Client } = require("pg");

const OUT = process.argv[2] || path.join(__dirname, "..", "db", "schema.sql");

// Extensions the app depends on; platform extensions (vault, pg_stat_statements) are excluded.
const APP_EXTENSIONS = ["pg_trgm", "pgcrypto", "uuid-ossp"];

async function exportSchema(client) {
  const out = [];
  const q = async (sql) => (await client.query(sql)).rows;

  out.push(
    "-- db/schema.sql — canonical schema snapshot (generated by scripts/export-schema.js; do not edit by hand)",
    `-- Generated: ${new Date().toISOString()}`,
    ""
  );

  // 1. Extensions
  const exts = await q("SELECT extname FROM pg_extension");
  for (const { extname } of exts) {
    if (APP_EXTENSIONS.includes(extname)) {
      out.push(`CREATE EXTENSION IF NOT EXISTS "${extname}";`);
    }
  }
  out.push("");

  // 2. Sequences (owned-by links are restored after tables)
  const seqs = await q(`
    SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'S' ORDER BY 1`);
  for (const { relname } of seqs) {
    out.push(`CREATE SEQUENCE IF NOT EXISTS public.${relname};`);
  }
  out.push("");

  // 3. Functions (excluding extension-owned ones)
  const fns = await q(`
    SELECT pg_get_functiondef(p.oid) AS def
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public' AND p.prokind = 'f'
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')
    ORDER BY p.proname`);
  for (const { def } of fns) out.push(`${def.trim()};`, "");

  // 4. Tables with columns, defaults and NOT NULL
  const tables = await q(`
    SELECT c.oid, c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r' ORDER BY 1`);
  for (const t of tables) {
    const cols = await q(`
      SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull,
             a.attgenerated, pg_get_expr(d.adbin, d.adrelid) AS def
      FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
      WHERE a.attrelid = ${t.oid} AND a.attnum > 0 AND NOT a.attisdropped
      ORDER BY a.attnum`);
    const lines = cols.map(
      (c) =>
        `  ${c.attname} ${c.type}` +
        (c.def && c.attgenerated === "s"
          ? ` GENERATED ALWAYS AS (${c.def}) STORED`
          : c.def
          ? ` DEFAULT ${c.def}`
          : "") +
        (c.attnotnull ? " NOT NULL" : "")
    );
    out.push(
      `CREATE TABLE IF NOT EXISTS public.${t.relname} (\n${lines.join(",\n")}\n);`,
      ""
    );
  }

  // 5. Constraints: primary/unique/check first, foreign keys after every table exists
  const cons = await q(`
    SELECT conrelid::regclass::text AS tbl, conname, contype, pg_get_constraintdef(oid) AS def
    FROM pg_constraint WHERE connamespace = 'public'::regnamespace AND contype IN ('p','u','c','f')
    ORDER BY CASE contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 ELSE 3 END, 1, 2`);
  for (const c of cons) {
    out.push(`ALTER TABLE ${c.tbl} ADD CONSTRAINT ${c.conname} ${c.def};`);
  }
  out.push("");

  // 6. Indexes not owned by constraints
  const idx = await q(`
    SELECT i.indexdef FROM pg_indexes i
    JOIN pg_class ic ON ic.relname = i.indexname
    JOIN pg_namespace n ON n.oid = ic.relnamespace AND n.nspname = i.schemaname
    WHERE i.schemaname = 'public'
      AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = ic.oid)
    ORDER BY i.tablename, i.indexname`);
  for (const { indexdef } of idx) out.push(`${indexdef};`);
  out.push("");

  // 7. Triggers
  const trg = await q(`
    SELECT pg_get_triggerdef(t.oid) AS def FROM pg_trigger t
    JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND NOT t.tgisinternal ORDER BY c.relname, t.tgname`);
  for (const { def } of trg) out.push(`${def};`);
  out.push("");

  // 8. Views (e.g. agency_outbound_daily)
  const views = await q(`
    SELECT viewname, definition FROM pg_views WHERE schemaname = 'public' ORDER BY viewname`);
  for (const v of views) out.push(`CREATE OR REPLACE VIEW public.${v.viewname} AS\n${v.definition.trim()}`, "");

  return out.join("\n");
}

async function main() {
  const client = new Client({
    connectionString: process.env.DATABASE_URL,
    ssl: { rejectUnauthorized: false }
  });
  await client.connect();
  try {
    await client.query("BEGIN READ ONLY");
    const ddl = await exportSchema(client);
    await client.query("ROLLBACK");
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, ddl);
    console.log(`Schema written to ${OUT} (${ddl.split("\n").length} lines)`);
  } finally {
    await client.end();
  }
}

if (require.main === module) {
  main().catch((err) => {
    console.error("Schema export failed:", err.message);
    process.exit(1);
  });
}

module.exports = { exportSchema };
