/**
 * Builds the 2-tab report dispatched after bulk Excel ingestion:
 * Tab 1: Added Units (Active inventory ready for WhatsApp searches and flyers)
 * Tab 2: Rejected Rows (Exact Excel row numbers, error reasons, and missing fields)
 */
async function buildBulkIngestionReport({
  addedListings = [],
  rejectedRows = [],
  agency = {},
  broker = {},
  lang = "ar"
}) {
  const isEn = lang === "en";
  const workbook = new ExcelJS.Workbook();
  workbook.creator = agency.name || "AqarChat Ingestion Engine";
  workbook.created = new Date();

  /* ------------------------------------------------------------------ */
  /* TAB 1: Successfully Added Listings                                 */
  /* ------------------------------------------------------------------ */
  const addedSheet = workbook.addWorksheet(
    isEn ? "Imported Units" : "الوحدات التي تمت إضافتها",
    {
      views: [{ rightToLeft: !isEn }]
    }
  );

  const addedHeaders = isEn
    ? [
        "Assigned Code",
        "Unit Title",
        "Price (EGP)",
        "Area (sqm)",
        "Rooms",
        "Location",
        "Status"
      ]
    : [
        "كود الوحدة المعتمد",
        "عنوان الوحدة",
        "السعر (ج.م)",
        "المساحة (م²)",
        "الغرف",
        "الموقع والكمبوند",
        "الحالة"
      ];

  const addedHeaderRow = addedSheet.addRow(addedHeaders);
  addedHeaderRow.height = 24;
  addedHeaderRow.eachCell((cell) => {
    cell.fill = STYLES.headerFill;
    cell.font = STYLES.headerFont;
    cell.alignment = { horizontal: "center", vertical: "middle" };
    cell.border = STYLES.borderHeader;
  });

  addedListings.forEach((item, idx) => {
    const row = addedSheet.addRow([
      item.code,
      item.title || "-",
      Number(item.price_value) || 0,
      Number(item.area_value) || 0,
      Number(item.bedrooms) || 0,
      item.location || item.compound || "-",
      isEn ? "Active" : "جاهزة للبحث والكتالوج"
    ]);

    row.height = 20;
    const isZebra = idx % 2 === 1;
    row.eachCell((cell, colNumber) => {
      cell.border = STYLES.borderThin;
      cell.font = { name: "Calibri", size: 10 };
      if (isZebra) cell.fill = STYLES.zebraFill;

      if (colNumber === 3) {
        cell.numFmt = "#,##0";
        cell.alignment = { horizontal: "right", vertical: "middle" };
      } else if (colNumber === 4 || colNumber === 5) {
        cell.alignment = { horizontal: "center", vertical: "middle" };
      } else {
        cell.alignment = {
          horizontal: isEn ? "left" : "right",
          vertical: "middle"
        };
      }
    });
  });

  autoFitColumns(addedSheet, 14, 3);

  /* ------------------------------------------------------------------ */
  /* TAB 2: Rejected Rows & Validation Errors                           */
  /* ------------------------------------------------------------------ */
  const rejectedSheet = workbook.addWorksheet(
    isEn ? "Rejected Rows" : "الصفوف المرفوضة والأخطاء",
    {
      views: [{ rightToLeft: !isEn }]
    }
  );

  const rejectedHeaders = isEn
    ? [
        "Excel Row #",
        "Given Code",
        "Rejection Reason",
        "Missing / Invalid Field",
        "Provided Text Details"
      ]
    : [
        "رقم الصف بالإكسيل",
        "الكود المرفق",
        "سبب الرفض",
        "الحقل المفقود أو غير الصالح",
        "البيانات المسجلة"
      ];

  const rejHeaderRow = rejectedSheet.addRow(rejectedHeaders);
  rejHeaderRow.height = 24;
  rejHeaderRow.eachCell((cell) => {
    cell.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: "FF991B1B" } // Crimson Dark
    };
    cell.font = STYLES.headerFont;
    cell.alignment = { horizontal: "center", vertical: "middle" };
    cell.border = STYLES.borderHeader;
  });

  rejectedRows.forEach((errItem) => {
    const row = rejectedSheet.addRow([
      errItem.rowNumber || "-",
      errItem.code || "-",
      errItem.reason || (isEn ? "Validation Failed" : "بيانات غير مكتملة"),
      errItem.field || "-",
      errItem.rawDetails || "-"
    ]);

    row.height = 22;
    row.eachCell((cell, colNumber) => {
      cell.border = STYLES.borderThin;
      cell.fill = STYLES.errorFill;
      cell.font = STYLES.errorFont;

      if (colNumber === 1) {
        cell.alignment = { horizontal: "center", vertical: "middle" };
      } else {
        cell.alignment = {
          horizontal: isEn ? "left" : "right",
          vertical: "middle"
        };
      }
    });
  });

  autoFitColumns(rejectedSheet, 16, 4);

  return Buffer.from(await workbook.xlsx.writeBuffer());
}

