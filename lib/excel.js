/**
 * Replaces raw CSV export with a professional, formatted .xlsx spreadsheet
 * containing all agency listings with filters, summary totals, and number formats.
 */
async function buildAgencyInventoryWorkbook({
  listings = [],
  agency = {},
  broker = {},
  lang = "ar"
}) {
  const isEn = lang === "en";
  const workbook = new ExcelJS.Workbook();
  workbook.creator = agency.name || broker.name || "AqarChat";
  workbook.lastModifiedBy = broker.name || "Agent";
  workbook.created = new Date();

  const sheetTitle = isEn ? "Agency Inventory" : "مخزون الوكالة العقاري";
  const sheet = workbook.addWorksheet(sheetTitle, {
    views: [{ state: "frozen", ySplit: 5, rightToLeft: !isEn }]
  });

  // Top Branding Banner
  sheet.mergeCells("A1:N1");
  const bannerCell = sheet.getCell("A1");
  bannerCell.value = `${agency.name || "Aqar Real Estate"} | ${
    isEn ? "Master Inventory Report" : "تقرير المخزون العام للوكالة"
  }`;
  bannerCell.font = {
    name: "Calibri",
    size: 14,
    bold: true,
    color: { argb: "FF0F172A" }
  };
  bannerCell.alignment = {
    horizontal: isEn ? "left" : "right",
    vertical: "middle"
  };
  bannerCell.fill = STYLES.bannerFill;
  sheet.getRow(1).height = 32;

  sheet.mergeCells("A2:N2");
  const subBanner = sheet.getCell("A2");
  subBanner.value = `${isEn ? "Generated by:" : "تم الاستخراج بواسطة:"} ${
    broker.name || "Broker"
  } (${
    broker.contact_phone || broker.phone || ""
  }) | ${new Date().toLocaleDateString("en-GB")} | ${
    isEn ? "Total Units:" : "إجمالي المعروض:"
  } ${listings.length}`;
  subBanner.font = {
    name: "Calibri",
    size: 10,
    italic: true,
    color: { argb: "FF475569" }
  };
  subBanner.alignment = {
    horizontal: isEn ? "left" : "right",
    vertical: "middle"
  };
  sheet.getRow(2).height = 20;

  sheet.addRow([]); // Blank spacer row (Row 3)
  sheet.getRow(3).height = 8;

  // Table Headers (Row 4)
  const headers = isEn
    ? [
        "Code",
        "Title",
        "Property Type",
        "Purpose",
        "Price (EGP)",
        "Down Payment",
        "Installment / Qtr",
        "Years",
        "Area (sqm)",
        "Bedrooms",
        "Bathrooms",
        "Finishing",
        "Location / Compound",
        "Status",
        "Date Added"
      ]
    : [
        "كود الوحدة",
        "العنوان",
        "نوع العقار",
        "المعاملة",
        "السعر الإجمالي (ج.م)",
        "المقدم (ج.م)",
        "القسط ربع السنوي",
        "سنوات التقسيط",
        "المساحة (م²)",
        "الغرف",
        "الحمامات",
        "التشطيب",
        "الموقع والكمبوند",
        "الحالة",
        "تاريخ التسجيل"
      ];

  const headerRow = sheet.addRow(headers);
  headerRow.height = 26;
  headerRow.eachCell((cell) => {
    cell.fill = STYLES.headerFill;
    cell.font = STYLES.headerFont;
    cell.alignment = { horizontal: "center", vertical: "middle" };
    cell.border = STYLES.borderHeader;
  });

  // Data Rows (Row 5+)
  const TYPE_LABELS = {
    apartment: isEn ? "Apartment" : "شقة",
    villa: isEn ? "Villa" : "فيلا",
    townhouse: isEn ? "Townhouse" : "تاون هاوس",
    twinhouse: isEn ? "Twinhouse" : "توين هاوس",
    duplex: isEn ? "Duplex" : "دوبلكس",
    penthouse: isEn ? "Penthouse" : "بنتهاوس",
    chalet: isEn ? "Chalet" : "شاليه",
    studio: isEn ? "Studio" : "استوديو",
    office: isEn ? "Office" : "مكتب",
    commercial: isEn ? "Commercial" : "تجاري",
    land: isEn ? "Land" : "أرض"
  };

  const STATUS_LABELS = {
    active: isEn ? "Active" : "نشط",
    sold: isEn ? "Sold" : "تم البيع",
    archived: isEn ? "Archived" : "مؤرشف"
  };

  listings.forEach((l, idx) => {
    const det = l.details || {};
    const typeKey = String(l.property_type || "apartment").toLowerCase();
    const statusKey = String(l.status || "active").toLowerCase();
    const purpose =
      l.listing_type === "rent"
        ? isEn
          ? "Rent"
          : "إيجار"
        : isEn
        ? "Sale"
        : "بيع";

    const row = sheet.addRow([
      String(l.code || "").toUpperCase(),
      l.title || "-",
      TYPE_LABELS[typeKey] || l.property_type || "-",
      purpose,
      Number(l.price_value) || 0,
      Number(l.down_payment_value || det.down_payment_value) || 0,
      Number(l.installment_value || det.installment_value) || 0,
      Number(l.installment_years || det.installment_years) || 0,
      Number(l.area_value) || 0,
      Number(l.bedrooms) || 0,
      Number(det.bathrooms) || 0,
      det.finishing || l.finishing_type || "-",
      l.compound
        ? `${l.compound} - ${l.district || l.location || ""}`
        : l.location || "-",
      STATUS_LABELS[statusKey] || l.status || "-",
      l.created_at ? new Date(l.created_at).toISOString().slice(0, 10) : "-"
    ]);

    row.height = 22;
    const isZebra = idx % 2 === 1;

    row.eachCell((cell, colNumber) => {
      cell.border = STYLES.borderThin;
      cell.font = { name: "Calibri", size: 10 };
      if (isZebra) cell.fill = STYLES.zebraFill;

      // Currency number formats (Price, DP, Installment)
      if (colNumber === 5 || colNumber === 6 || colNumber === 7) {
        cell.numFmt = "#,##0";
        cell.alignment = { horizontal: "right", vertical: "middle" };
      } else if (
        colNumber === 8 ||
        colNumber === 9 ||
        colNumber === 10 ||
        colNumber === 11
      ) {
        cell.numFmt = "#,##0";
        cell.alignment = { horizontal: "center", vertical: "middle" };
      } else {
        cell.alignment = {
          horizontal: isEn ? "left" : "right",
          vertical: "middle"
        };
      }
    });
  });

  // Enable Auto-Filter on table header row
  sheet.autoFilter = {
    from: { row: 4, column: 1 },
    to: { row: 4 + listings.length, column: headers.length }
  };

  autoFitColumns(sheet, 12, 3);
  return Buffer.from(await workbook.xlsx.writeBuffer());
}

